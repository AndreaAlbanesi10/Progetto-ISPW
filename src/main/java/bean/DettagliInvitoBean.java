package bean;

public class DettagliInvitoBean extends InvitoBean {

    private String descrizioneShowcase;
    private String nomeCampo;
    private String indirizzo;
    private String citta;
    private String immCampo;

    public String getDescrizioneShowcase() {
        return descrizioneShowcase;
    }

    public void setDescrizioneShowcase(String descrizioneShowcase) {
        this.descrizioneShowcase = descrizioneShowcase;
    }

    public String getNomeCampo() {
        return nomeCampo;
    }

    public void setNomeCampo(String nomeCampo) {
        this.nomeCampo = nomeCampo;
    }

    public String getIndirizzo() {
        return indirizzo;
    }

    public void setIndirizzo(String indirizzo) {
        this.indirizzo = indirizzo;
    }

    public String getCitta() {
        return citta;
    }

    public void setCitta(String citta) {
        this.citta = citta;
    }

    public String getImmCampo() {
        return immCampo;
    }

    public void setImmCampo(String immCampo) {
        this.immCampo = immCampo;
    }

}
